# --------------------------------------------------------------------------- measurement helpers
def entrance_from_spec(spec):
    """(point, opening, todo) for a point 0.4 m inside the main exterior door, else the footprint centre."""
    W, D = spec['footprint']
    doors = []
    for w in spec.get('outerWalls', []):
        for o in w.get('openings', []):
            if o.get('type') == 'door':
                score = (bool(o.get('entrance')) or 'front' in o.get('id', ''),
                         o.get('swingSide') == 'interior', o['to'] - o['from'])
                doors.append((score, w, o))
    if not doors:
        return [round(W / 2, 3), round(D / 2, 3)], None, True
    doors.sort(key=lambda t: t[0], reverse=True)
    _, w, o = doors[0]
    mid = (o['from'] + o['to']) / 2.0
    if w['axis'] == 'x':
        inner = w['inner_z']
        sign = 1 if inner > w['line_z_outer'] else -1
        pt = [mid, inner + 0.4 * sign]
    else:
        inner = w['inner_x']
        sign = 1 if inner > w['line_x_outer'] else -1
        pt = [inner + 0.4 * sign, mid]
    return [round(pt[0], 3), round(pt[1], 3)], (w['id'], o['id']), False


def agreement_pct(mx, mz):
    return abs(mx - mz) / ((mx + mz) / 2.0) * 100.0


def openings_list(spec):
    out = []
    for w in spec.get('outerWalls', []) + spec.get('interiorWalls', []):
        for o in w.get('openings', []):
            out.append((w['id'], o))
    return out


# --------------------------------------------------------------------------- plan.md
def render_plan(tpl, ctx, areas):
    """Fill the template; return (text, unfilled placeholder list)."""
    # Replace the template's leading author comment with a generated note.
    tpl = re.sub(r'<!--.*?-->\n*', '', tpl, count=1, flags=re.S)
    tpl = tpl.replace('`~/property-build-work/{{PROPERTY_ID}}/`', '`%s/`' % ctx['WORKDIR'])
    # The area table row: expand from areas.json.
    rows = []
    for a in areas['areas']:
        scope = a['scope']
        if len(scope) > 160:
            scope = scope[:157].rsplit(' ', 1)[0] + ' ...'
        rows.append('| %s | `%s` | %s | %s |' % (a['title'], a['prefix'], a['lights'], scope.replace('|', '/')))
    tpl = re.sub(r'^\| \{\{AREA\}\} \|.*$', '\n'.join(rows), tpl, count=1, flags=re.M)

    def sub(m):
        inner = m.group(1)
        key = inner.split(',')[0].strip()
        if key in ctx and ctx[key] is not None:
            return str(ctx[key])
        if inner.startswith('production | local'):
            return 'production'
        if inner.startswith('single storey') and ctx.get('_storeys', 1) == 1:
            return 'single storey: do NOT set a floors list'
        return m.group(0)

    text = PH_RE.sub(sub, tpl)
    left = sorted(set('{{%s}}' % p for p in PH_RE.findall(text)) - {'{{PLACEHOLDER}}'})
    header = ('<!-- Generated by the build-property kit (new_property.py) on %s. Measured values come from '
              'spec.draft.json; spec.json is authoritative once reviewed. Still to fill: %s. Delete this comment '
              'when done. -->\n\n' % (ctx['TODAY'], ', '.join(left) if left else 'nothing'))
    lines = text.split('\n', 1)
    text = lines[0] + '\n\n' + header + (lines[1].lstrip('\n') if len(lines) > 1 else '')
    return text, left


