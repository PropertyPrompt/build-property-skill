    with open(os.path.join(KIT, 'templates', 'PLAN-TEMPLATE.md')) as f:
        tpl = f.read()
    plan_md, plan_left = render_plan(tpl, ctx, areas)
    plan_path = os.path.join(work, 'plan.md')
