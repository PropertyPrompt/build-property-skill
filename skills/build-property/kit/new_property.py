def die(msg, code=2):
    sys.stderr.write('new_property: %s\n' % msg)
    sys.exit(code)


def durable_or_die(path):
    """Refuse temp and scratchpad directories: working files there were wiped mid-build before."""
    for p in {os.path.abspath(path), os.path.realpath(path)}:
        for pre in TEMP_PREFIXES:
            if p == pre or p.startswith(pre + '/'):
                die('work root %s is a temp directory (%s). Use a durable folder such as %s.' % (path, pre, HOME_ROOT))
        if 'scratchpad' in p:
            die('work root %s is a scratchpad directory. Use a durable folder such as %s.' % (path, HOME_ROOT))


def write_json(path, obj):
    with open(path, 'w') as f:
        json.dump(obj, f, indent=1)
        f.write('\n')


def load_json(path):
    with open(path) as f:
        return json.load(f)


def fmt_m(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


