def cmd_init(a):
    if not a.plan or not a.name:
        die('--plan and --name are required with --id')
    if not ID_RE.match(a.id):
        die('--id must be 3-60 lowercase letters, numbers and single hyphens, starting and ending with a letter or '
            'number (it cannot be changed later)')
    if bool(a.width_ft) != bool(a.depth_ft) or bool(a.width_m) != bool(a.depth_m) or \
            bool(a.width_ft) == bool(a.width_m):
        die('give exactly one pair: --width-ft W --depth-ft D, or --width-m W --depth-m D (labelled outside size)')
    if not os.path.isfile(a.plan):
        die('plan image not found: %s' % a.plan)
    if a.storeys < 1:
        die('--storeys must be >= 1')
    root = os.path.abspath(os.path.expanduser(a.work_root))
    durable_or_die(root)
    work = os.path.join(root, a.id)
    if os.path.exists(work) and not a.force:
        die('%s already exists; pass --force to regenerate its generated files (spec.json, rooms.json, research, '
            'payloads and logs are kept)' % work)
    try:
        from PIL import Image
    except ImportError:
        die('Pillow is required for the plan measurer. Install it with: python3 -m pip install Pillow '
            '(add --user, or --break-system-packages on an externally managed Python, if that is refused)')

    for d in SUBDIRS:
        os.makedirs(os.path.join(work, d), exist_ok=True)
    plan_name = os.path.basename(a.plan)
    plan_copy = os.path.join(work, 'source', plan_name)
    if os.path.abspath(a.plan) != plan_copy:
        shutil.copy2(a.plan, plan_copy)
    with Image.open(plan_copy) as im:
        img_w, img_h = im.size

    if a.width_ft:
        width_m, depth_m = a.width_ft * FT, a.depth_ft * FT
        dims = '%s ft x %s ft = %.2f m x %.2f m' % (fmt_m(a.width_ft), fmt_m(a.depth_ft), width_m, depth_m)
        label = '%s ft x %s ft' % (fmt_m(a.width_ft), fmt_m(a.depth_ft))
    else:
        width_m, depth_m = a.width_m, a.depth_m
        dims = '%.2f m x %.2f m (%.1f ft x %.1f ft)' % (width_m, depth_m, width_m / FT, depth_m / FT)
        label = '%s m x %s m' % (fmt_m(width_m), fmt_m(depth_m))

    # 3. measure
    draft_path = os.path.join(work, 'spec.draft.json')
    overlay = os.path.join(work, 'spec-overlay.png')
    cmd = [sys.executable, os.path.join(KIT, 'measure', 'measure_plan.py'), plan_copy,
           '--property-id', a.id, '--source-file', 'source/' + plan_name, '--ceiling', str(a.ceiling),
           '--out', draft_path, '--debug-png', overlay]
    cmd += ['--width-ft', str(a.width_ft), '--depth-ft', str(a.depth_ft)] if a.width_ft else \
        ['--width-m', str(a.width_m), '--depth-m', str(a.depth_m)]
    if a.crop:
        cmd += ['--crop', a.crop]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        die('measure_plan.py failed:\n%s%s' % (r.stdout, r.stderr), 1)
    measure_out = r.stdout.strip()
    spec = load_json(draft_path)

    # Extra keys the rest of the kit reads; the reviewer completes them.
    ext_style = None
    if a.style:
        ext_style = re.sub(r'^(exterior|interior)\b\s*:?\s*', '', a.style.split(';', 1)[0].strip(), flags=re.I)
    areas = generic_areas(ext_style, a.market)
    spec['idPrefixes'] = dict([('shell-outer', 'so-'), ('shell-inner', 'si-')] +
                              [(x['key'], x['prefix']) for x in areas['areas']] +
                              [('lighting', 'lt-'), ('library', 'm-')])
    if a.style:
        parts = [re.sub(r'^(exterior|interior)\b\s*:?\s*', '', p.strip(), flags=re.I) for p in a.style.split(';', 1)]
