def wall_rect(w, default_t):
    """[x1, z1, x2, z2] of a spec wall."""
    if 'line_z_outer' in w or 'line_x_outer' in w:
        if w['axis'] == 'x':
            z0, z1 = sorted((w['line_z_outer'], w['inner_z']))
            return [w['from'], z0, w['to'], z1], z1 - z0
        x0, x1 = sorted((w['line_x_outer'], w['inner_x']))
        return [x0, w['from'], x1, w['to']], x1 - x0
    t = w.get('thickness', default_t)
    if w['axis'] == 'x':
        c = w['center_z']
        return [w['from'], c - t / 2, w['to'], c + t / 2], t
    c = w['center_x']
    return [c - t / 2, w['from'], c + t / 2, w['to']], t


def angled_overlap(spec, w, poly):
    """How far a room polygon reaches into an angled wall (0 if it does not): the room is turned into
    the wall's frame, where the wall is the rectangle [0, length] x [band], and clipped to it. Outer
    walls run from their outside face line toward the footprint centre; interior walls are centred."""
    (ax, az), (bx, bz) = w['start'], w['end']
    length = math.hypot(bx - ax, bz - az)
    if length < 1e-9:
        return 0
    ux, uz = (bx - ax) / length, (bz - az) / length

    def local(x, z):
        dx, dz = x - ax, z - az
        return (dx * ux + dz * uz, -dx * uz + dz * ux)
    t = w['thickness']
    if w['kind'] == 'outer':
        cx, cz = spec['footprint'][0] / 2, spec['footprint'][1] / 2
        band = (0, t) if local(cx, cz)[1] > 0 else (-t, 0)
    else:
        band = (-t / 2, t / 2)
    pts = [local(x, z) for x, z in poly]
    overlaps = clip_rect(strips(pts), (0, band[0], length, band[1]))
    return max((min(max(p[0] for p in pc) - min(p[0] for p in pc), max(p[1] for p in pc) - min(p[1] for p in pc))
                for pc in overlaps), default=0)


def check_spec(spec, schema):
    """Return (errors, warnings)."""
    v = Validator(schema)
    v.check(spec, schema, '')
    errors = list(v.errors)
    warns = []
    if errors:
        return errors, warns
    W, D = spec['footprint']
    tol = 0.005
    if spec.get('draft'):
        warns.append('draft is still true: set it to false once reviewed.')
    if not spec.get('rooms'):
        errors.append('rooms is empty: fill rooms from the plan labels.')

    ids = {}

    def check_openings(w, lo, hi):
        for o in w['openings']:
            ids.setdefault(o['id'], []).append('opening')
            where = '%s/%s' % (w['id'], o['id'])
            if not o['from'] < o['to']:
                errors.append('%s: from %.3f must be < to %.3f' % (where, o['from'], o['to']))
            if o['from'] < lo - tol or o['to'] > hi + tol:
                errors.append('%s: %.3f-%.3f is outside its wall %.3f-%.3f' % (
                    where, o['from'], o['to'], lo, hi))
            if o['type'] == 'window' and not o['sill'] < o['head']:
                errors.append('%s: sill %.3f must be below head %.3f' % (where, o['sill'], o['head']))
            if o.get('head', 0) > spec['ceilingHeight'] + tol:
                errors.append('%s: head %.3f above the ceiling %.3f' % (where, o['head'], spec['ceilingHeight']))
            if o.get('needsReview'):
                warns.append('%s: needsReview is still set.' % where)
        ops = sorted(w['openings'], key=lambda o: o['from'])
        for p, q in zip(ops, ops[1:]):
            if q['from'] < p['to'] - tol:
                errors.append('%s: openings %s and %s overlap' % (w['id'], p['id'], q['id']))

    for w in spec['outerWalls'] + spec['interiorWalls']:
        ids.setdefault(w['id'], []).append('wall')
        check_openings(w, w['from'], w['to'])
        if not w['from'] < w['to']:
            errors.append('%s: wall from must be < to' % w['id'])
    for w in spec.get('angledWalls', []):
        ids.setdefault(w['id'], []).append('wall')
        length = math.hypot(w['end'][0] - w['start'][0], w['end'][1] - w['start'][1])
        if length < 0.1:
            errors.append('%s: angled wall is shorter than 0.1 m' % w['id'])
        for x, z in (w['start'], w['end']):
            if x < -tol or z < -tol or x > W + tol or z > D + tol:
                errors.append('%s: end [%.3f, %.3f] lies outside the footprint' % (w['id'], x, z))
        check_openings(w, 0, length)
    if spec.get('angledWalls') and not any(r.get('polygon') for r in spec.get('rooms', [])):
        warns.append('angledWalls are given but no room has a polygon: give the rooms they bound a polygon')
    for r in spec.get('rooms', []):
        ids.setdefault(r['id'], []).append('room')
    for k, kinds in ids.items():
        if len(kinds) > 1 and len(set(kinds)) == 1:
            errors.append('duplicate %s id "%s"' % (kinds[0], k))

    walls = [(w['id'],) + wall_rect(w, spec['wallThickness']['interior'])
             for w in spec['outerWalls'] + spec['interiorWalls']]
    rooms = []
    for r in spec.get('rooms', []):
        b = r.get('bounds')
        if not b:
            errors.append('room %s has no bounds [x1, z1, x2, z2]' % r['id'])
            continue
        x1, z1, x2, z2 = b
        if not (x1 < x2 and z1 < z2):
            errors.append('room %s bounds must have x1 < x2 and z1 < z2' % r['id'])
            continue
        if x1 < -tol or z1 < -tol or x2 > W + tol or z2 > D + tol:
            errors.append('room %s bounds lie outside the %.3f x %.3f footprint' % (r['id'], W, D))
        rooms.append((r['id'], b))
        for x, z in r.get('polygon') or []:
            if not (x1 - tol <= x <= x2 + tol and z1 - tol <= z <= z2 + tol):
                errors.append('room %s polygon point [%.3f, %.3f] lies outside its bounds' % (r['id'], x, z))
                break
        room_parts = strips(r['polygon']) if r.get('polygon') else None
        for aw in spec.get('angledWalls', []):
            depth = angled_overlap(spec, aw, r.get('polygon') or [[x1, z1], [x2, z1], [x2, z2], [x1, z2]])
            t = aw['thickness']
            if depth > t / 2 + 0.02:
                errors.append('room %s overlaps angled wall %s by %.3f m (more than half its %.3f m thickness): '
                              'its polygon should stop at the wall face' % (r['id'], aw['id'], depth, t))
            elif depth > 0.03:
                warns.append('room %s overlaps angled wall %s by %.3f m' % (r['id'], aw['id'], depth))
        for wid, (wx1, wz1, wx2, wz2), t in walls:
            ox = min(x2, wx2) - max(x1, wx1)
            oz = min(z2, wz2) - max(z1, wz1)
            if ox <= 0.02 or oz <= 0.02:
                continue
            depth = min(ox, oz)          # penetration across the wall's thickness (or a short stub)
            if room_parts is not None:
                overlaps = clip_rect(room_parts, (wx1, wz1, wx2, wz2))
                depth = max((min(max(p[0] for p in pc) - min(p[0] for p in pc),
                                 max(p[1] for p in pc) - min(p[1] for p in pc))
                             for pc in overlaps), default=0)
            if depth > t / 2 + 0.02:
                errors.append('room %s overlaps wall %s by %.3f m (more than half its %.3f m thickness): bounds '
                              'should stop at the wall face' % (r['id'], wid, depth, t))
            elif depth > 0.03:
                warns.append('room %s overlaps wall %s by %.3f m' % (r['id'], wid, depth))
    for i, (a, ba) in enumerate(rooms):
        for b, bb in rooms[i + 1:]:
            ox = min(ba[2], bb[2]) - max(ba[0], bb[0])
            oz = min(ba[3], bb[3]) - max(ba[1], bb[1])
            if ox > 0.05 and oz > 0.05:
                warns.append('rooms %s and %s overlap (%.2f x %.2f m)' % (a, b, ox, oz))
    for k, b in (spec.get('drawnItems') or {}).items():
        if not (b[0] < b[2] and b[1] < b[3]):
            errors.append('drawnItems %s must be [x1, z1, x2, z2] with x1 < x2 and z1 < z2' % k)
    return errors, warns


def run_check(work, quiet=False):
    path = os.path.join(work, 'spec.json')
    if not os.path.isfile(path):
        return None, ['spec.json not found in %s' % work], []
    try:
        spec = load_json(path)
    except ValueError as e:
        return None, ['spec.json is not valid JSON: %s' % e], []
    errors, warns = check_spec(spec, load_json(os.path.join(KIT, 'measure', 'spec.schema.json')))
    return spec, errors, warns


def cmd_check_spec(a):
    work = workdir_for(a, a.check_spec)
    spec, errors, warns = run_check(work)
    for w in warns:
        print('warning: ' + w)
    for e in errors:
        print('ERROR: ' + e)
    if errors:
        print('spec.json: %d error(s), %d warning(s)' % (len(errors), len(warns)))
        sys.exit(1)
    n_open = len(openings_list(spec))
    print('spec.json OK: %d outer walls, %d interior walls, %d openings, %d rooms, %d drawn items; %d warning(s)' % (
        len(spec['outerWalls']), len(spec['interiorWalls']), n_open, len(spec.get('rooms', [])),
        len(spec.get('drawnItems') or {}), len(warns)))


