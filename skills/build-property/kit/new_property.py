#!/usr/bin/env python3
"""Start a new property build from a floor-plan image (one command).

Init:
    python3 new_property.py --plan PATH.png --id PROPERTY_ID --name "Display name" \\
        (--width-ft W --depth-ft D | --width-m W --depth-m D) \\
        [--work-root DIR] [--ceiling 2.44] \\
        [--market "USA, USD, US retailers"] [--currency USD] \\
        [--style "exterior ...; interior ..."] [--storeys 1] [--crop x0,y0,x1,y1] [--force]

Status / spec check:
    python3 new_property.py --status PROPERTY_ID [--work-root ...]
    python3 new_property.py --check-spec PROPERTY_ID [--work-root ...]

Init creates <work-root>/<id>/ with source/ (a copy of the plan), research/ gen/ payloads/
validation/ renders/ review/, and writes:
  spec.draft.json, spec-overlay.png   measure/measure_plan.py output (review it, save as spec.json)
  plan.md                             templates/PLAN-TEMPLATE.md with every measurable placeholder filled
  areas.json                          generic role-based areas (tailor to the rooms the plan has)
  create_property.draft.json          create_property arguments (rooms still to fill)
  build-args.json                     args for workflow/build.js and workflow/review.js
  MANUAL-EDITS.md, STATUS.md          edit log header and the remaining-steps checklist

--work-root defaults to $PROPERTY_BUILD_WORK_ROOT, else ~/property-build-work. It must persist
between sessions: in a hosted session whose home folder is wiped, use the project's shared files.

Python 3.9+, standard library plus Pillow (for the plan measurer).
"""
